//! Generates compile-time lookup tables from tools/*.json.
//!
//! - baidu_audio.json -> baidu_tones.rs: pinyin -> tone bitmask (which real-voice mp3s exist)
//! - speak_map.json   -> examples.rs:   pinyin -> example hanzi (a first-tone homophone)

use std::collections::HashMap;
use std::fs;
use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=tools/baidu_audio.json");
    println!("cargo:rerun-if-changed=tools/speak_map.json");
    gen_baidu();
    gen_examples();
}

/// Extract "key": "value" pairs from a flat JSON object.
/// Values here are pinyin / single hanzi, with no escapes, so a byte scan on
/// ASCII quotes is safe even though the content is UTF-8.
fn parse_flat_object(text: &str) -> Vec<(String, String)> {
    let bytes = text.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] != b'"' {
            i += 1;
            continue;
        }
        let ks = i + 1;
        let mut j = ks;
        while j < bytes.len() && bytes[j] != b'"' {
            j += 1;
        }
        if j >= bytes.len() {
            break;
        }
        let key = &text[ks..j];
        let mut k = j + 1;
        while k < bytes.len() && bytes[k] != b':' {
            k += 1;
        }
        if k >= bytes.len() {
            break;
        }
        let mut v = k + 1;
        while v < bytes.len() && bytes[v] != b'"' {
            v += 1;
        }
        if v >= bytes.len() {
            break;
        }
        let vs = v + 1;
        let mut e = vs;
        while e < bytes.len() && bytes[e] != b'"' {
            e += 1;
        }
        if e >= bytes.len() {
            break;
        }
        let value = &text[vs..e];
        if !key.is_empty() && !value.is_empty() && value != "-" {
            out.push((key.to_owned(), value.to_owned()));
        }
        i = e + 1;
    }
    out
}

fn gen_baidu() {
    let manifest = Path::new("tools/baidu_audio.json");
    let mut entries: Vec<(String, u8)> = Vec::new();
    if manifest.exists() {
        let text = fs::read_to_string(manifest).expect("read baidu_audio.json");
        // Values are tone arrays like "[1, 2, 3]": scan quoted keys followed by brackets.
        let bytes = text.as_bytes();
        let mut i = 0;
        while i < bytes.len() {
            if bytes[i] == b'"' {
                let start = i + 1;
                let mut j = start;
                while j < bytes.len() && bytes[j] != b'"' {
                    j += 1;
                }
                let key = &text[start..j];
                let mut k = j + 1;
                while k < bytes.len() && bytes[k] != b'[' {
                    k += 1;
                }
                if k >= bytes.len() {
                    break;
                }
                let mut e = k + 1;
                let mut mask = 0u8;
                while e < bytes.len() && bytes[e] != b']' {
                    if bytes[e].is_ascii_digit() {
                        let tone = bytes[e] - b'0';
                        if (1..=4).contains(&tone) {
                            mask |= 1 << (tone - 1);
                        }
                    }
                    e += 1;
                }
                if !key.is_empty() && mask != 0 {
                    entries.push((key.to_owned(), mask));
                }
                i = e + 1;
            } else {
                i += 1;
            }
        }
    }
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let mut lines = Vec::new();
    lines.push("// @generated by build.rs from tools/baidu_audio.json. Do not edit.".to_owned());
    lines.push("pub static BAIDU_TONES: &[(&str, u8)] = &[".to_owned());
    for (pinyin, mask) in &entries {
        lines.push(format!("    ({:?}, {}),", pinyin, mask));
    }
    lines.push("];".to_owned());
    lines.push(String::new());
    lines.push("/// Returns the tone bitmask for a pinyin, or 0 when unavailable.".to_owned());
    lines.push("pub fn baidu_mask(pinyin: &str) -> u8 {".to_owned());
    lines.push("    BAIDU_TONES".to_owned());
    lines.push("        .binary_search_by(|(key, _)| (*key).cmp(pinyin))".to_owned());
    lines.push("        .map(|idx| BAIDU_TONES[idx].1)".to_owned());
    lines.push("        .unwrap_or(0)".to_owned());
    lines.push("}".to_owned());
    lines.push(String::new());

    // 四声辨析题只用四声音频齐全、且已有例字的音节，避免答题时回退错声调。
    let examples: HashMap<String, String> = if Path::new("tools/speak_map.json").exists() {
        let text = fs::read_to_string("tools/speak_map.json").expect("read speak_map.json");
        parse_flat_object(&text).into_iter().collect()
    } else {
        HashMap::new()
    };
    let mut tone_entries: Vec<(&str, &str)> = entries
        .iter()
        .filter(|(_, mask)| *mask == 0b1111)
        .filter_map(|(pinyin, _)| {
            examples
                .get(pinyin.as_str())
                .map(|hanzi| (pinyin.as_str(), hanzi.as_str()))
        })
        .collect();
    tone_entries.sort_by(|a, b| a.0.cmp(b.0));

    let mut tone_lines = Vec::new();
    tone_lines.push(
        "// @generated by build.rs from tools/baidu_audio.json + speak_map.json. Do not edit."
            .to_owned(),
    );
    tone_lines.push("pub static TONE_EXAMPLES: &[(&str, &str)] = &[".to_owned());
    for (pinyin, hanzi) in &tone_entries {
        tone_lines.push(format!("    (\"{}\", \"{}\"),", pinyin, hanzi));
    }
    tone_lines.push("];".to_owned());
    tone_lines.push(String::new());

    let out = std::env::var("OUT_DIR").expect("OUT_DIR");
    fs::write(Path::new(&out).join("baidu_tones.rs"), lines.join("\n"))
        .expect("write baidu_tones.rs");
    fs::write(
        Path::new(&out).join("tone_examples.rs"),
        tone_lines.join("\n"),
    )
    .expect("write tone_examples.rs");
}

fn gen_examples() {
    let manifest = Path::new("tools/speak_map.json");
    let mut entries: Vec<(String, String)> = Vec::new();
    if manifest.exists() {
        let text = fs::read_to_string(manifest).expect("read speak_map.json");
        entries = parse_flat_object(&text);
    }
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let mut lines = Vec::new();
    lines.push("// @generated by build.rs from tools/speak_map.json. Do not edit.".to_owned());
    lines.push("pub static EXAMPLES: &[(&str, &str)] = &[".to_owned());
    for (pinyin, hanzi) in &entries {
        lines.push(format!("    (\"{}\", \"{}\"),", pinyin, hanzi));
    }
    lines.push("];".to_owned());
    lines.push(String::new());
    lines.push("/// Returns the example hanzi for a pinyin, or None when unavailable.".to_owned());
    lines.push("pub fn example_char(pinyin: &str) -> Option<&'static str> {".to_owned());
    lines.push("    EXAMPLES".to_owned());
    lines.push("        .binary_search_by(|(key, _)| (*key).cmp(pinyin))".to_owned());
    lines.push("        .ok()".to_owned());
    lines.push("        .map(|idx| EXAMPLES[idx].1)".to_owned());
    lines.push("}".to_owned());
    lines.push(String::new());

    let out = std::env::var("OUT_DIR").expect("OUT_DIR");
    fs::write(Path::new(&out).join("examples.rs"), lines.join("\n")).expect("write examples.rs");
}
