#!/usr/bin/env python3
"""Single source of truth for pinyin data.

Generates:
  tools/pinyin_table.json  - consumed by gen_audio.py
  src/data/pinyin_data.rs  - consumed by the Rust app

The matrix maps each initial to the finals it legally combines with,
following the 普通话音节表 (standard Mandarin syllable table).
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

INITIALS = [
    "b", "p", "m", "f", "d", "t", "n", "l", "g", "k", "h", "j",
    "q", "x", "zh", "ch", "sh", "r", "z", "c", "s", "y", "w",
]

FINALS = [
    "a", "o", "e", "i", "u", "ü", "ai", "ei", "ui", "ao", "ou", "iu",
    "ie", "üe", "er", "an", "en", "in", "un", "ün", "ang", "eng", "ing", "ong",
]

# initial -> finals that form a legal two-part syllable
MATRIX: dict[str, list[str]] = {
    "b": ["a", "o", "i", "u", "ai", "ei", "ao", "ie", "an", "en", "in", "ang", "eng", "ing"],
    "p": ["a", "o", "i", "u", "ai", "ei", "ao", "ou", "ie", "an", "en", "in", "ang", "eng", "ing"],
    "m": ["a", "o", "e", "i", "u", "ai", "ei", "ao", "ou", "iu", "ie", "an", "en", "in", "ang", "eng", "ing"],
    "f": ["a", "o", "u", "ei", "ou", "an", "en", "ang", "eng"],
    "d": ["a", "e", "i", "u", "ai", "ei", "ui", "ao", "ou", "iu", "ie", "an", "en", "un", "ang", "eng", "ing", "ong"],
    "t": ["a", "e", "i", "u", "ai", "ui", "ao", "ou", "ie", "an", "un", "ang", "eng", "ing", "ong"],
    "n": ["a", "e", "i", "u", "ü", "ai", "ei", "ao", "ou", "iu", "ie", "üe", "an", "en", "in", "ang", "eng", "ing", "ong"],
    "l": ["a", "o", "e", "i", "u", "ü", "ai", "ei", "ao", "ou", "iu", "ie", "üe", "an", "en", "in", "un", "ang", "eng", "ing", "ong"],
    "g": ["a", "e", "u", "ai", "ei", "ui", "ao", "ou", "an", "en", "un", "ang", "eng", "ong"],
    "k": ["a", "e", "u", "ai", "ei", "ui", "ao", "ou", "an", "en", "un", "ang", "eng", "ong"],
    "h": ["a", "e", "u", "ai", "ei", "ui", "ao", "ou", "an", "en", "un", "ang", "eng", "ong"],
    "j": ["i", "ü", "iu", "ie", "üe", "in", "ün", "ing"],
    "q": ["i", "ü", "iu", "ie", "üe", "in", "ün", "ing"],
    "x": ["i", "ü", "iu", "ie", "üe", "in", "ün", "ing"],
    "zh": ["a", "e", "i", "u", "ai", "ei", "ui", "ao", "ou", "an", "en", "un", "ang", "eng", "ong"],
    "ch": ["a", "e", "i", "u", "ai", "ui", "ao", "ou", "an", "en", "un", "ang", "eng", "ong"],
    "sh": ["a", "e", "i", "u", "ai", "ei", "ui", "ao", "ou", "an", "en", "un", "ang", "eng"],
    "r": ["e", "i", "u", "ui", "ao", "ou", "an", "en", "un", "ang", "eng", "ong"],
    "z": ["a", "e", "i", "u", "ai", "ei", "ui", "ao", "ou", "an", "en", "un", "ang", "eng", "ong"],
    "c": ["a", "e", "i", "u", "ai", "ui", "ao", "ou", "an", "en", "un", "ang", "eng", "ong"],
    "s": ["a", "e", "i", "u", "ai", "ui", "ao", "ou", "an", "en", "un", "ang", "eng", "ong"],
    "y": ["a", "e", "i", "u", "ü", "ai", "ei", "ao", "ou", "ie", "üe", "an", "en", "in", "un", "ang", "eng", "ing", "ong"],
    "w": ["a", "o", "u", "ai", "ei", "an", "en", "ang", "eng"],
}

# 零声母音节 (syllables with no initial)
ZERO_SYLLABLES = FINALS.copy()


def compose(initial: str, final: str) -> str:
    """Spell an initial+final pair into its written syllable."""
    # j/q/x/y + ü spelled with u in writing: jü -> ju, qün -> qun, yüe -> yue
    if initial in ("j", "q", "x", "y") and "ü" in final:
        return initial + final.replace("ü", "u")
    return initial + final


def build() -> None:
    syllables: list[str] = list(ZERO_SYLLABLES)
    for initial in INITIALS:
        for final in MATRIX[initial]:
            s = compose(initial, final)
            if s not in syllables:
                syllables.append(s)

    table = {
        "initials": INITIALS,
        "finals": FINALS,
        "syllables": syllables,
        "matrix": MATRIX,
        "zeroSyllables": ZERO_SYLLABLES,
    }
    (ROOT / "tools" / "pinyin_table.json").write_text(
        json.dumps(table, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    def rust_list(name: str, items: list[str], typ: str = "&[&str]") -> str:
        body = "\n".join(f'    "{x}",' for x in items)
        return f"pub const {name}: {typ} = &[\n{body}\n];\n"

    rs = "// Generated by tools/build_table.py -- do not edit by hand.\n\n"
    rs += rust_list("INITIALS", INITIALS)
    rs += "\n" + rust_list("FINALS", FINALS)
    rs += "\n" + rust_list("SYLLABLES", syllables)
    rs += "\n" + rust_list("ZERO_SYLLABLES", ZERO_SYLLABLES)
    rs += "\n/// For each initial, the finals it legally combines with.\n"
    rs += "pub static MATRIX: &[(&str, &[&str])] = &[\n"
    for initial in INITIALS:
        finals = ", ".join(f'"{f}"' for f in MATRIX[initial])
        rs += f'    ("{initial}", &[{finals}]),\n'
    rs += "];\n"
    (ROOT / "src" / "data" / "pinyin_data.rs").write_text(rs, encoding="utf-8")

    print(f"initials={len(INITIALS)} finals={len(FINALS)} syllables={len(syllables)}")


if __name__ == "__main__":
    build()
